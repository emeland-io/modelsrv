type Artifact struct {
	// UUID that uniquely identifies the artifact.
	ArtifactID uuid.UUID `emeland:"id,required"`
	// A human-readable name of the artifact.
	DisplayName string `emeland:"name,required"`
	// A description of the artifact.
	Description string `emeland:"description"`
	// Hash of the binary object in the format algorithm:hex (e.g. "SHA256:9e9b...").
	Hash string `emeland:"pattern=^[A-Za-z0-9]+:[0-9a-f]+$,example=SHA256:9e9b755d63b36acf30c12a9a3fc379243714c1c6d3dd72861da637f336ebb35b"`
	// A set of key-value pairs for storing additional metadata about the artifact.
	Annotations annotations.Annotations `emeland:"annotations"`
}

// Represents a context in the EmELand model. A context is a high-level categorization or domain that groups systems and other entities based on shared characteristics or purposes.
//
// +emeland:resource
// +emeland:dir=context
// +emeland:handler
// +emeland:handleralias=mdlctx
// +emeland:client
// +emeland:list=/landscape/contexts
type Context struct {
	// An UUID that uniquely identifies the context. It should be generated and assigned when the context is created and must remain constant throughout the context's lifecycle. The field is optional in some contexts, such as when creating a new context where the ID may be generated by the system itself.
	ContextID uuid.UUID `emeland:"id,required"`
	// The human-readable name of the context.
	DisplayName string `emeland:"name,required"`
	// A brief description of the context's purpose and scope.
	Description string `emeland:"description"`
	// The UUID of the context type that defines the characteristics of this context.
	Type uuid.UUID `emeland:"required"`
	// The UUID of the parent context, if applicable. This field is optional and may be omitted if the context has no parent. It establishes a hierarchical relationship between contexts.
	Parent uuid.UUID
	// A set of key-value pairs for storing additional metadata about the context.
	Annotations annotations.Annotations `emeland:"annotations"`
}
